package com.iqoo.insideme.ai.core

import java.io.File
import java.security.MessageDigest

enum class ActionType {
    CREATE_TASK, CREATE_REMINDER, ADD_NOTE, GENERATE_REPORT
}

data class ProposedAction(
    val type: ActionType,
    val reason: String,
    val evidenceIds: List<String>,
    val requiresConfirmation: Boolean = true
)

/**
 * 13.19 Action Safety Policy Validator
 * The LLM must NEVER directly execute actions. It only proposes them.
 */
class ActionValidator {
    fun validateAction(action: ProposedAction): Boolean {
        // Enforce that all state-mutating actions generated by the LLM require explicit user approval
        if (action.type == ActionType.CREATE_TASK && !action.requiresConfirmation) {
            println("POLICY VIOLATION: LLM attempted to execute an action without user confirmation.")
            return false
        }
        return true
    }
}

